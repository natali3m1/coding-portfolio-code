module sevseg (
    input  logic [3:0] D,
    output logic [6:0] S
);

always_comb begin
    case (D)
        4'h0: S = 7'b1000000;
        4'h1: S = 7'b1111001;
        4'h2: S = 7'b0100100;
        4'h3: S = 7'b0110000;
        4'h4: S = 7'b0011001;
        4'h5: S = 7'b0010010;
        4'h6: S = 7'b0000010;
        4'h7: S = 7'b1111000;
        4'h8: S = 7'b0000000;
        4'h9: S = 7'b0010000;
        4'hA: S = 7'b0001000;
        4'hB: S = 7'b0000011;
        4'hC: S = 7'b1000110;
        4'hD: S = 7'b0100001;
        4'hE: S = 7'b0000110;
        4'hF: S = 7'b0001110;
        default: S = 7'b1111111;
    endcase
end
